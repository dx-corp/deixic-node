import { access, readFile } from "node:fs/promises";
import { resolve } from "node:path";

const packageRoot = process.cwd();
const sources = [
  resolve(packageRoot, "../../../gen/ts/console/v1/console_pb.ts"),
  resolve(packageRoot, "../../../gen/ts/deixic/v1/deixic_pb.ts"),
];

for (const source of sources) {
  await access(source);
  const content = await readFile(source, "utf8");
  if (!content.startsWith("// @generated by protoc-gen-es")) {
    throw new Error(`Expected current generated descriptor source: ${source}`);
  }
}
